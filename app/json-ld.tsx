// Renders schema.org structured data. JSON-LD is data, not executed script;
// "<" is escaped so the content cannot close the tag early.
export function JsonLd({ data }: { data: object | null }) {
  if (!data) return null;
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, "\\u003c"),
      }}
    />
  );
}
